    [TestMethod]
    public void TestStride2Padding0Kernel2()
    {
        var layer = new MaxPool2D(2, 2, 0);
        var input = Tensor<float>.FromRectangularArray(new float[,] {
            {12, 20, 30, 00},
            {08, 12, 02, 00},
            {34, 70, 37, 04},
            {112, 100, 25, 12}
        });
        var result = Tensor<float>.FromRectangularArray(new float[,] {
            {20, 30},
            {112, 37}
        });

        var outputs = layer.Forward(input);

        Assert.AreEqual(true, outputs.Equals(result, 0.001f));
    }

